// Generates apps/ios/BanbeApp/Models/EventAnnouncementTemplates.swift from
// src/lib/eventAnnouncements.js so web + iOS templates never drift.
// Run after editing the web catalogue:  node scripts/gen-announcement-templates-ios.mjs
import { writeFileSync } from 'node:fs';
import { ANNOUNCEMENT_CATEGORIES, ANNOUNCEMENT_TEMPLATES, ANNOUNCEMENT_MAX } from '../src/lib/eventAnnouncements.js';

const q = (s) => JSON.stringify(s);
const out = `// GENERATED by scripts/gen-announcement-templates-ios.mjs from src/lib/eventAnnouncements.js — do not edit by hand.
import Foundation

struct AnnouncementCategory: Identifiable, Hashable {
    let id: String, vi: String, en: String
}

struct AnnouncementTemplate: Identifiable, Hashable {
    let id: String, category: String, vi: String, en: String, keywords: String
}

enum EventAnnouncements {
    static let maxLength = ${ANNOUNCEMENT_MAX}
    static let quickIDs = ["starting-soon", "delay-15", "doors-open"]

    static let categories: [AnnouncementCategory] = [
${ANNOUNCEMENT_CATEGORIES.map(c => `        AnnouncementCategory(id: ${q(c.id)}, vi: ${q(c.vi)}, en: ${q(c.en)}),`).join('\n')}
    ]

    static let templates: [AnnouncementTemplate] = [
${ANNOUNCEMENT_TEMPLATES.map(t => `        AnnouncementTemplate(id: ${q(t.id)}, category: ${q(t.category)}, vi: ${q(t.vi)}, en: ${q(t.en)}, keywords: ${q(t.keywords)}),`).join('\n')}
    ]

    private static func fold(_ s: String) -> String {
        s.replacingOccurrences(of: "đ", with: "d").replacingOccurrences(of: "Đ", with: "D")
            .folding(options: [.diacriticInsensitive, .caseInsensitive], locale: nil)
    }

    /// Accent/case-insensitive match over both languages + keywords, within an optional category.
    static func filter(query: String, category: String?) -> [AnnouncementTemplate] {
        let words = fold(query).split(whereSeparator: { $0.isWhitespace }).map(String.init)
        return templates.filter { t in
            if let category, category != "all", t.category != category { return false }
            if words.isEmpty { return true }
            let hay = fold("\\(t.vi) \\(t.en) \\(t.keywords)")
            return words.allSatisfy { hay.contains($0) }
        }
    }
}
`;
writeFileSync(new URL('../apps/ios/BanbeApp/Models/EventAnnouncementTemplates.swift', import.meta.url), out);
console.log('wrote EventAnnouncementTemplates.swift');
