// Generates apps/ios/BanbeApp/Models/HelpContent.swift from src/data/help/*.js
// so the iOS Guides/Q&A text can never drift from the web. Run after editing
// the web content:  node scripts/gen-help-content-ios.mjs
import { writeFileSync } from 'node:fs';
import { GUIDES, FAQ_SECTIONS } from '../src/data/help/index.js';

const q = (s) => JSON.stringify(s);
const pairs = (items) => `[${items.map(([vi, en]) => `[${q(vi)}, ${q(en)}]`).join(', ')}]`;
const block = (b) => {
  switch (b[0]) {
    case 'ul': case 'ol': return `.${b[0]}(${pairs(b[1])})`;
    case 'q': return `.q(${q(b[1])}, ${q(b[2])}, ${q(b[3])}, ${q(b[4])})`;
    default: return `.${b[0]}(${q(b[1])}, ${q(b[2])})`;
  }
};
const section = (s) => `        HelpSection(id: ${q(s.id)}, vi: ${q(s.vi)}, en: ${q(s.en)}, blocks: [\n${s.blocks.map(b => `            ${block(b)},`).join('\n')}\n        ]),`;
const doc = (name, d) => `    static let ${name} = HelpDoc(\n        vi: ${q(d.vi)}, en: ${q(d.en)},\n        introVi: ${q(d.introVi)}, introEn: ${q(d.introEn)},\n        adminOnly: ${!!d.adminOnly},\n        sections: [\n${d.sections.map(section).join('\n')}\n        ]\n    )`;

const out = `// GENERATED by scripts/gen-help-content-ios.mjs from src/data/help/*.js — do not edit by hand.
import Foundation

enum HelpBlock {
    case p(String, String)
    case h(String, String)
    case tip(String, String)
    case ul([[String]])
    case ol([[String]])
    case q(String, String, String, String)
}

struct HelpSection: Identifiable {
    let id: String
    let vi: String
    let en: String
    let blocks: [HelpBlock]
}

struct HelpDoc {
    let vi: String
    let en: String
    let introVi: String
    let introEn: String
    let adminOnly: Bool
    let sections: [HelpSection]
}

enum HelpContent {
${doc('personal', GUIDES.personal)}

${doc('host', GUIDES.host)}

${doc('admin', GUIDES.admin)}

${doc('faq', { vi: 'Hỏi & Đáp', en: 'Q&A', introVi: 'Câu hỏi thường gặp. Dùng ô tìm kiếm để lọc nhanh.', introEn: 'Frequently asked questions. Use the search box to filter.', sections: FAQ_SECTIONS })}

    static func guide(_ key: String?) -> HelpDoc? {
        switch key {
        case "personal": return personal
        case "host": return host
        case "admin": return admin
        default: return nil
        }
    }
}
`;
writeFileSync(new URL('../apps/ios/BanbeApp/Models/HelpContent.swift', import.meta.url), out);
console.log('ok');
