// Generates group-f-events.sql (dry run, ends in ROLLBACK) and the matching rollback from group-f-events.json.
// Run from the repo root: node supabase/drafts/v23-testdata/group-f-generate.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const F = JSON.parse(readFileSync('supabase/drafts/v23-testdata/group-f-events.json', 'utf8'));
const LABEL = { supper: 'Supper club', music: 'Nhạc', fashion: 'Thời trang', gallery: 'Phòng tranh', popup: 'Pop-up' };

let bad = 0;
for (const e of F.events) {
  const L = e.description.length;
  if (L < 250 || L > 450) { console.log('length', e.key, L); bad++; }
  const t = [e.description, e.intro, ...e.greeting, ...e.included.flat(), ...Object.values(e.details).flat()].join('|');
  if (/[—–;]| - /.test(t)) { console.log('dash or semicolon', e.key); bad++; }
}
if (bad) process.exit(1);

const q = s => `$v23$${s}$v23$`;
const keys = F.events.map(e => `'${e.key}'`).join(',');
const photos = [...new Set(F.events.flatMap(e => e.photos))].map(p => `'event-photos/${p}'`).join(',');

let a = `-- v2.3 test data, group F: ${F.events.length} new live test events owned by ${F.organizer} (the test admin account),
-- generated by group-f-generate.mjs from group-f-events.json. Each row copies the structural columns of a same-type
-- template event (palette, approval, hold_minutes, country, reservation_criteria, tz, currency) and overrides all content.
-- Photos reference EXISTING event-photos storage paths (no uploads). Also renames the organizer
-- ${F.organizerRename.from} -> ${F.organizerRename.to}. NOT a migration. Ends in ROLLBACK (dry run).
-- Rollback: supabase/rollbacks/v23_testdata_group_f_rollback.sql
BEGIN;
DO $$ DECLARE v text; BEGIN
  IF EXISTS (SELECT 1 FROM events WHERE id IN (${keys}) OR slug IN (${keys})) THEN RAISE EXCEPTION 'some new keys already exist'; END IF;
  IF (SELECT name FROM organizers WHERE id = '${F.organizer}') <> ${q(F.organizerRename.from)} THEN RAISE EXCEPTION 'organizer name changed'; END IF;
  SELECT string_agg(p, ', ') INTO v FROM unnest(ARRAY[${photos}]) p
   WHERE NOT EXISTS (SELECT 1 FROM event_photos ep WHERE ep.storage_path = p);
  IF v IS NOT NULL THEN RAISE EXCEPTION 'unknown photo paths: %', v; END IF;
END $$;
UPDATE organizers SET name = ${q(F.organizerRename.to)} WHERE id = '${F.organizer}';
`;

for (const e of F.events) {
  const tpl = F.templates[e.type];
  const items = e.included.map(([label, detail]) => ({ label, detail }));
  const words = [...new Set([...e.name.split(/\s+/).map(w => w.replace(/[,:]/g, '')).filter(w => w.length > 1), e.area, LABEL[e.type], ...items.map(i => i.label)])];
  const o = {
    id: e.key, key: e.key, slug: e.key, organizer_id: F.organizer, name: e.name,
    category: LABEL[e.type], cat_key: e.type, cat_label: LABEL[e.type],
    description: e.description, intro: e.intro, included: items.map(i => i.label).join(' ▪︎ '), included_items: items,
    area: e.area, neighborhood: e.neighborhood, lat: e.lat, lng: e.lng,
    price_vnd: e.price, price_cents: e.price * 100, capacity: e.capacity, seats_remaining: e.capacity,
    status: 'live', visibility: 'public', cancelled_at: null, cancel_reason: '', reviewed_by: null,
    cover_image: `event-photos/${e.photos[0]}`, cover_r2_ref: null, keywords: words,
    chat_greeting: e.greeting[0], chat_greeting_en: e.greeting[1], details: { v: 1, ...e.details },
    removed_at: null, removed_by: null, removed_from_status: null, withdrawn_at: null,
    resubmission_count: 0, resubmission_window_start: null, admin_remind_count: 0, last_admin_reminded_at: null, address_verified: false,
  };
  a += `INSERT INTO events SELECT (jsonb_populate_record(NULL::events, to_jsonb(t) || ${q(JSON.stringify(o))}::jsonb || jsonb_build_object(
  'event_date', (now() AT TIME ZONE t.tz)::date + ${e.n}, 'event_time', '${e.time}'::time,
  'starts_at', (((now() AT TIME ZONE t.tz)::date + ${e.n}) + '${e.time}'::time) AT TIME ZONE t.tz,
  'created_at', now(), 'submitted_at', now(), 'reviewed_at', now()))).* FROM events t WHERE t.key = '${tpl}';
INSERT INTO event_photos (event_id, storage_path, sort_order) VALUES ${e.photos.map((p, i) => `('${e.key}', 'event-photos/${p}', ${i})`).join(', ')};
`;
}

a += `SELECT e.key, e.cat_key, e.name, to_char(e.starts_at AT TIME ZONE e.tz, 'Dy DD Mon HH24:MI') AS venue_time, e.price_vnd, e.capacity,
       (SELECT count(*) FROM event_photos p WHERE p.event_id = e.id) AS photos,
       (SELECT count(*) FROM events x WHERE x.status = 'live' AND x.visibility = 'public' AND x.cat_key = e.cat_key) AS live_of_type,
       (SELECT count(DISTINCT organizer_id) FROM events x WHERE x.status = 'live' AND x.visibility = 'public' AND x.cat_key = e.cat_key) AS hosts_of_type,
       (SELECT name FROM organizers WHERE id = e.organizer_id) AS host
  FROM events e WHERE e.key IN (${keys}) ORDER BY e.starts_at;
ROLLBACK;
`;
writeFileSync('supabase/drafts/v23-testdata/group-f-events.sql', a);

const r = `-- Rollback for supabase/drafts/v23-testdata/group-f-events.sql
-- Deletes the ${F.events.length} new events and their photo rows ONLY if nothing hangs off them yet
-- (bookings, dispute threads, refund send requests, favorites, threads, check-ins). Otherwise it refuses,
-- and those events go through the admin removal flow (note 54). Restores the organizer name.
BEGIN;
DO $$ DECLARE v text; BEGIN
  SELECT string_agg(t || ':' || n, ', ') INTO v FROM (
    SELECT 'bookings' t, count(*) n FROM bookings WHERE event_id IN (${keys})
    UNION ALL SELECT 'dispute_threads', count(*) FROM dispute_threads WHERE event_id IN (${keys})
    UNION ALL SELECT 'refund_send_requests', count(*) FROM event_refund_send_requests WHERE event_id IN (${keys})
    UNION ALL SELECT 'favorites', count(*) FROM favorites WHERE event_id IN (${keys})
    UNION ALL SELECT 'threads', count(*) FROM threads WHERE event_id IN (${keys})
    UNION ALL SELECT 'check_ins', count(*) FROM check_ins WHERE event_id IN (${keys})
  ) x WHERE n > 0;
  IF v IS NOT NULL THEN RAISE EXCEPTION 'refusing, records hang off the new events: %', v; END IF;
END $$;
DELETE FROM event_photos WHERE event_id IN (${keys});
DELETE FROM events WHERE id IN (${keys});
UPDATE organizers SET name = ${q(F.organizerRename.from)} WHERE id = '${F.organizer}' AND name = ${q(F.organizerRename.to)};
COMMIT;
`;
writeFileSync('supabase/rollbacks/v23_testdata_group_f_rollback.sql', r);
console.log('generated', F.events.length, 'events');
